import { z } from 'zod';
import { createAction } from 'nango';

const ProviderTodoSchema = z
    .object({
        _id: z.string(),
        userId: z.string().optional(),
        teamId: z.string().nullable().optional(),
        title: z.string().optional(),
        description: z.string().nullable().optional(),
        dueDate: z.string().nullable().optional(),
        originalDueDate: z.string().nullable().optional(),
        isPersonal: z.boolean().optional(),
        createdBy: z.string().nullable().optional(),
        repeat: z.string().nullable().optional(),
        seriesId: z.string().nullable().optional(),
        companyId: z.string().optional(),
        ordinal: z.number().optional(),
        userOrdinal: z.number().optional(),
        milestoneId: z.string().nullable().optional(),
        autoGenerated: z.boolean().optional(),
        dueDateChanged: z.boolean().optional(),
        comments: z.array(z.unknown()).optional(),
        archived: z.boolean().optional(),
        archivedDate: z.string().nullable().optional(),
        archivedByUserId: z.string().nullable().optional(),
        completed: z.boolean().optional(),
        completedDate: z.string().nullable().optional(),
        completedByUserId: z.string().nullable().optional(),
        deleted: z.boolean().optional(),
        deletedDate: z.string().nullable().optional(),
        deletedByUserId: z.string().nullable().optional(),
        imported: z.boolean().optional(),
        createdByUserId: z.string().optional(),
        createdDate: z.string().optional(),
        followers: z.array(z.string()).optional(),
        _version: z.number().optional()
    })
    .passthrough();

const InputSchema = z.object({
    id: z.string().describe('To-Do ID. Example: "6a6174ad545a6c26e85e387e"')
});

const OutputSchema = z.object({
    id: z.string(),
    userId: z.string().optional(),
    teamId: z.string().optional(),
    title: z.string().optional(),
    description: z.string().optional(),
    dueDate: z.string().optional(),
    originalDueDate: z.string().optional(),
    isPersonal: z.boolean().optional(),
    createdBy: z.string().optional(),
    repeat: z.string().optional(),
    seriesId: z.string().optional(),
    companyId: z.string().optional(),
    ordinal: z.number().optional(),
    userOrdinal: z.number().optional(),
    milestoneId: z.string().optional(),
    autoGenerated: z.boolean().optional(),
    dueDateChanged: z.boolean().optional(),
    comments: z.array(z.unknown()).optional(),
    archived: z.boolean().optional(),
    archivedDate: z.string().optional(),
    archivedByUserId: z.string().optional(),
    completed: z.boolean().optional(),
    completedDate: z.string().optional(),
    completedByUserId: z.string().optional(),
    deleted: z.boolean().optional(),
    deletedDate: z.string().optional(),
    deletedByUserId: z.string().optional(),
    imported: z.boolean().optional(),
    createdByUserId: z.string().optional(),
    createdDate: z.string().optional(),
    followers: z.array(z.string()).optional(),
    version: z.number().optional()
});

const action = createAction({
    description: 'Retrieve a single to-do by id.',
    version: '1.0.0',
    input: InputSchema,
    output: OutputSchema,

    exec: async (nango, input): Promise<z.infer<typeof OutputSchema>> => {
        const response = await nango.get({
            // https://help.ninety.io/en/articles/15505694-api-reference-and-access
            endpoint: `/v1/todos/${encodeURIComponent(input.id)}`,
            retries: 3
        });

        if (!response.data) {
            throw new nango.ActionError({
                type: 'not_found',
                message: 'To-Do not found',
                id: input.id
            });
        }

        const todo = ProviderTodoSchema.parse(response.data);

        return {
            id: todo._id,
            ...(todo.userId !== undefined && { userId: todo.userId }),
            ...(todo.teamId != null && { teamId: todo.teamId }),
            ...(todo.title !== undefined && { title: todo.title }),
            ...(todo.description != null && { description: todo.description }),
            ...(todo.dueDate != null && { dueDate: todo.dueDate }),
            ...(todo.originalDueDate != null && { originalDueDate: todo.originalDueDate }),
            ...(todo.isPersonal !== undefined && { isPersonal: todo.isPersonal }),
            ...(todo.createdBy != null && { createdBy: todo.createdBy }),
            ...(todo.repeat != null && { repeat: todo.repeat }),
            ...(todo.seriesId != null && { seriesId: todo.seriesId }),
            ...(todo.companyId !== undefined && { companyId: todo.companyId }),
            ...(todo.ordinal !== undefined && { ordinal: todo.ordinal }),
            ...(todo.userOrdinal !== undefined && { userOrdinal: todo.userOrdinal }),
            ...(todo.milestoneId != null && { milestoneId: todo.milestoneId }),
            ...(todo.autoGenerated !== undefined && { autoGenerated: todo.autoGenerated }),
            ...(todo.dueDateChanged !== undefined && { dueDateChanged: todo.dueDateChanged }),
            ...(todo.comments !== undefined && { comments: todo.comments }),
            ...(todo.archived !== undefined && { archived: todo.archived }),
            ...(todo.archivedDate != null && { archivedDate: todo.archivedDate }),
            ...(todo.archivedByUserId != null && { archivedByUserId: todo.archivedByUserId }),
            ...(todo.completed !== undefined && { completed: todo.completed }),
            ...(todo.completedDate != null && { completedDate: todo.completedDate }),
            ...(todo.completedByUserId != null && { completedByUserId: todo.completedByUserId }),
            ...(todo.deleted !== undefined && { deleted: todo.deleted }),
            ...(todo.deletedDate != null && { deletedDate: todo.deletedDate }),
            ...(todo.deletedByUserId != null && { deletedByUserId: todo.deletedByUserId }),
            ...(todo.imported !== undefined && { imported: todo.imported }),
            ...(todo.createdByUserId !== undefined && { createdByUserId: todo.createdByUserId }),
            ...(todo.createdDate !== undefined && { createdDate: todo.createdDate }),
            ...(todo.followers !== undefined && { followers: todo.followers }),
            ...(todo._version !== undefined && { version: todo._version })
        };
    }
});

export type NangoActionLocal = Parameters<(typeof action)['exec']>[0];
export default action;
