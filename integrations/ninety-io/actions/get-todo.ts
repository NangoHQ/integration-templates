import { z } from 'zod';
import { createAction } from 'nango';

const InputSchema = z.object({
    id: z.string().describe('To-Do ID. Example: "6a6174ad545a6c26e85e387e"')
});

const ProviderTodoSchema = z.object({
    _id: z.string(),
    userId: z.string(),
    teamId: z.string().nullable(),
    title: z.string(),
    description: z.string(),
    dueDate: z.string(),
    originalDueDate: z.string(),
    isPersonal: z.boolean(),
    createdBy: z.string().nullable(),
    repeat: z.string(),
    seriesId: z.string().nullable(),
    companyId: z.string(),
    ordinal: z.number(),
    userOrdinal: z.number(),
    milestoneId: z.string().nullable(),
    autoGenerated: z.boolean(),
    dueDateChanged: z.boolean(),
    comments: z.array(z.unknown()),
    archived: z.boolean(),
    archivedDate: z.string().nullable(),
    archivedByUserId: z.string().nullable(),
    completed: z.boolean(),
    completedDate: z.string().nullable(),
    completedByUserId: z.string().nullable(),
    deleted: z.boolean(),
    deletedDate: z.string().nullable(),
    deletedByUserId: z.string().nullable(),
    imported: z.boolean(),
    createdByUserId: z.string(),
    createdDate: z.string(),
    followers: z.array(z.string()),
    _version: z.number()
});

const OutputSchema = z.object({
    _id: z.string(),
    userId: z.string(),
    teamId: z.string().optional(),
    title: z.string(),
    description: z.string(),
    dueDate: z.string(),
    originalDueDate: z.string(),
    isPersonal: z.boolean(),
    createdBy: z.string().optional(),
    repeat: z.string(),
    seriesId: z.string().optional(),
    companyId: z.string(),
    ordinal: z.number(),
    userOrdinal: z.number(),
    milestoneId: z.string().optional(),
    autoGenerated: z.boolean(),
    dueDateChanged: z.boolean(),
    comments: z.array(z.unknown()),
    archived: z.boolean(),
    archivedDate: z.string().optional(),
    archivedByUserId: z.string().optional(),
    completed: z.boolean(),
    completedDate: z.string().optional(),
    completedByUserId: z.string().optional(),
    deleted: z.boolean(),
    deletedDate: z.string().optional(),
    deletedByUserId: z.string().optional(),
    imported: z.boolean(),
    createdByUserId: z.string(),
    createdDate: z.string(),
    followers: z.array(z.string()),
    _version: z.number()
});

const action = createAction({
    description: 'Retrieve a single to-do by id.',
    version: '1.0.0',
    input: InputSchema,
    output: OutputSchema,

    exec: async (nango, input): Promise<z.infer<typeof OutputSchema>> => {
        const response = await nango.get({
            // https://help.ninety.io/en/articles/15505694-api-reference-and-access
            endpoint: `/v1/todos/${encodeURIComponent(input.id)}`,
            retries: 3
        });

        if (!response.data) {
            throw new nango.ActionError({
                type: 'not_found',
                message: 'To-Do not found',
                id: input.id
            });
        }

        const todo = ProviderTodoSchema.parse(response.data);

        return {
            _id: todo._id,
            userId: todo.userId,
            title: todo.title,
            description: todo.description,
            dueDate: todo.dueDate,
            originalDueDate: todo.originalDueDate,
            isPersonal: todo.isPersonal,
            repeat: todo.repeat,
            companyId: todo.companyId,
            ordinal: todo.ordinal,
            userOrdinal: todo.userOrdinal,
            autoGenerated: todo.autoGenerated,
            dueDateChanged: todo.dueDateChanged,
            comments: todo.comments,
            archived: todo.archived,
            completed: todo.completed,
            deleted: todo.deleted,
            imported: todo.imported,
            createdByUserId: todo.createdByUserId,
            createdDate: todo.createdDate,
            followers: todo.followers,
            _version: todo._version,
            ...(todo.teamId != null && { teamId: todo.teamId }),
            ...(todo.createdBy != null && { createdBy: todo.createdBy }),
            ...(todo.seriesId != null && { seriesId: todo.seriesId }),
            ...(todo.milestoneId != null && { milestoneId: todo.milestoneId }),
            ...(todo.archivedDate != null && { archivedDate: todo.archivedDate }),
            ...(todo.archivedByUserId != null && { archivedByUserId: todo.archivedByUserId }),
            ...(todo.completedDate != null && { completedDate: todo.completedDate }),
            ...(todo.completedByUserId != null && { completedByUserId: todo.completedByUserId }),
            ...(todo.deletedDate != null && { deletedDate: todo.deletedDate }),
            ...(todo.deletedByUserId != null && { deletedByUserId: todo.deletedByUserId })
        };
    }
});

export type NangoActionLocal = Parameters<(typeof action)['exec']>[0];
export default action;
