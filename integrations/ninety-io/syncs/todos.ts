import { createSync } from 'nango';
import { z } from 'zod';

const ProviderTodoSchema = z.object({
    _id: z.string(),
    title: z.string(),
    description: z.string().nullable().optional(),
    teamId: z.string().nullable().optional(),
    userId: z.string().nullable().optional(),
    companyId: z.string().nullable().optional(),
    createdDate: z.string().nullable().optional(),
    dueDate: z.string().nullable().optional(),
    originalDueDate: z.string().nullable().optional(),
    completedDate: z.string().nullable().optional(),
    completed: z.boolean().nullable().optional(),
    completedByUserId: z.string().nullable().optional(),
    deleted: z.boolean().nullable().optional(),
    deletedDate: z.string().nullable().optional(),
    deletedByUserId: z.string().nullable().optional(),
    archived: z.boolean().nullable().optional(),
    archivedDate: z.string().nullable().optional(),
    archivedByUserId: z.string().nullable().optional(),
    createdByUserId: z.string().nullable().optional(),
    createdBy: z.string().nullable().optional(),
    milestoneId: z.string().nullable().optional(),
    isPersonal: z.boolean().nullable().optional(),
    repeat: z.string().nullable().optional(),
    seriesId: z.string().nullable().optional(),
    autoGenerated: z.boolean().nullable().optional(),
    dueDateChanged: z.boolean().nullable().optional(),
    imported: z.boolean().nullable().optional(),
    followers: z.array(z.string()).nullable().optional(),
    teamName: z.string().nullable().optional(),
    _version: z.number().nullable().optional(),
    ordinal: z.number().nullable().optional(),
    userOrdinal: z.number().nullable().optional(),
    comments: z.array(z.unknown()).nullable().optional()
});

const TodoSchema = z.object({
    id: z.string(),
    title: z.string().optional(),
    description: z.string().optional(),
    teamId: z.string().optional(),
    userId: z.string().optional(),
    companyId: z.string().optional(),
    createdDate: z.string().optional(),
    dueDate: z.string().optional(),
    originalDueDate: z.string().optional(),
    completedDate: z.string().optional(),
    completed: z.boolean().optional(),
    completedByUserId: z.string().optional(),
    archived: z.boolean().optional(),
    archivedDate: z.string().optional(),
    archivedByUserId: z.string().optional(),
    createdByUserId: z.string().optional(),
    milestoneId: z.string().optional(),
    isPersonal: z.boolean().optional(),
    repeat: z.string().optional(),
    seriesId: z.string().optional(),
    autoGenerated: z.boolean().optional(),
    dueDateChanged: z.boolean().optional(),
    imported: z.boolean().optional(),
    followers: z.array(z.string()).optional(),
    teamName: z.string().optional(),
    ordinal: z.number().optional(),
    userOrdinal: z.number().optional()
});

const CheckpointSchema = z.object({
    nextPage: z.number().int().positive()
});

const sync = createSync({
    description: 'Sync to-dos (personal and team-based).',
    version: '1.0.0',
    frequency: 'every hour',
    autoStart: true,
    checkpoint: CheckpointSchema,
    models: {
        Todo: TodoSchema
    },

    exec: async (nango) => {
        // Blocker: the Ninety.io Public API exposes no modified-timestamp field
        // on to-dos (only createdDate), and POST /v1/todos/query does not accept
        // an updatedSince or changed-since filter, so this remains a full refresh.
        // The endpoint supports page/pageSize (1-based page) but returns a bare
        // array with no total count, so we page until a short (or empty) page.
        const checkpoint = await nango.getCheckpoint();
        let hasCheckpoint = checkpoint != null;

        await nango.trackDeletesStart('Todo');

        let page = checkpoint?.nextPage ?? 1;
        const pageSize = 100;

        while (true) {
            // https://help.ninety.io/en/articles/15505694-api-reference-and-access
            const response = await nango.post({
                endpoint: '/v1/todos/query',
                data: { page, pageSize },
                retries: 3
            });

            const parseResult = z.array(ProviderTodoSchema).safeParse(response.data);
            if (!parseResult.success) {
                throw new Error(`Failed to parse todos response: ${parseResult.error.message}`);
            }

            const todos = parseResult.data;
            if (todos.length === 0) {
                break;
            }

            const todosToSave = [];
            for (const todo of todos) {
                // Soft-deleted to-dos remain returned by the query with deleted: true.
                // Skip them so that trackDeletesEnd correctly marks them deleted.
                if (todo.deleted === true) {
                    continue;
                }

                todosToSave.push({
                    id: todo._id,
                    ...(todo.title !== undefined && { title: todo.title }),
                    ...(todo.description !== undefined && todo.description !== null && { description: todo.description }),
                    ...(todo.teamId !== undefined && todo.teamId !== null && { teamId: todo.teamId }),
                    ...(todo.userId !== undefined && todo.userId !== null && { userId: todo.userId }),
                    ...(todo.companyId !== undefined && todo.companyId !== null && { companyId: todo.companyId }),
                    ...(todo.createdDate !== undefined && todo.createdDate !== null && { createdDate: todo.createdDate }),
                    ...(todo.dueDate !== undefined && todo.dueDate !== null && { dueDate: todo.dueDate }),
                    ...(todo.originalDueDate !== undefined && todo.originalDueDate !== null && { originalDueDate: todo.originalDueDate }),
                    ...(todo.completedDate !== undefined && todo.completedDate !== null && { completedDate: todo.completedDate }),
                    ...(todo.completed !== undefined && todo.completed !== null && { completed: todo.completed }),
                    ...(todo.completedByUserId !== undefined && todo.completedByUserId !== null && { completedByUserId: todo.completedByUserId }),
                    ...(todo.archived !== undefined && todo.archived !== null && { archived: todo.archived }),
                    ...(todo.archivedDate !== undefined && todo.archivedDate !== null && { archivedDate: todo.archivedDate }),
                    ...(todo.archivedByUserId !== undefined && todo.archivedByUserId !== null && { archivedByUserId: todo.archivedByUserId }),
                    ...(todo.createdByUserId !== undefined && todo.createdByUserId !== null && { createdByUserId: todo.createdByUserId }),
                    ...(todo.milestoneId !== undefined && todo.milestoneId !== null && { milestoneId: todo.milestoneId }),
                    ...(todo.isPersonal !== undefined && todo.isPersonal !== null && { isPersonal: todo.isPersonal }),
                    ...(todo.repeat !== undefined && todo.repeat !== null && { repeat: todo.repeat }),
                    ...(todo.seriesId !== undefined && todo.seriesId !== null && { seriesId: todo.seriesId }),
                    ...(todo.autoGenerated !== undefined && todo.autoGenerated !== null && { autoGenerated: todo.autoGenerated }),
                    ...(todo.dueDateChanged !== undefined && todo.dueDateChanged !== null && { dueDateChanged: todo.dueDateChanged }),
                    ...(todo.imported !== undefined && todo.imported !== null && { imported: todo.imported }),
                    ...(todo.followers !== undefined && todo.followers !== null && { followers: todo.followers }),
                    ...(todo.teamName !== undefined && todo.teamName !== null && { teamName: todo.teamName }),
                    ...(todo.ordinal !== undefined && todo.ordinal !== null && { ordinal: todo.ordinal }),
                    ...(todo.userOrdinal !== undefined && todo.userOrdinal !== null && { userOrdinal: todo.userOrdinal })
                });
            }

            if (todosToSave.length > 0) {
                await nango.batchSave(todosToSave, 'Todo');
            }

            if (todos.length < pageSize) {
                break;
            }

            const nextPage = page + 1;
            await nango.saveCheckpoint({ nextPage });
            hasCheckpoint = true;
            page = nextPage;
        }

        if (hasCheckpoint) {
            await nango.clearCheckpoint();
        }

        await nango.trackDeletesEnd('Todo');
    }
});

export type NangoSyncLocal = Parameters<(typeof sync)['exec']>[0];
export default sync;
