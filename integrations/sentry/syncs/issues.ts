import { createSync } from 'nango';
import type { ProxyConfiguration } from 'nango';
import { z } from 'zod';

/**
 * Sync strategy: full refresh.
 * GET /0/organizations/{organization_id_or_slug}/issues/ exposes no
 * updated-since/modified-after filter (verified against Sentry's official
 * OpenAPI spec and docs: only environment, project, statsPeriod, start, end,
 * groupStatsPeriod, shortIdLookup, query, viewId, sort, limit, expand, collapse
 * and cursor are supported), and issue mutations (status, assignment) do not
 * reliably move an issue's lastSeen sort position. Every run therefore crawls
 * all issues from page 1 (sort=date, cursor pagination via the Link header)
 * and wraps the crawl in trackDeletesStart()/trackDeletesEnd() so records that
 * disappeared at Sentry are removed only after a complete crawl.
 */

const IssueAssigneeSchema = z
    .object({
        type: z.string().optional().describe('Type of the assignee actor, either "user" or "team". Example: "user"'),
        id: z.string().optional().describe('ID of the assigned user or team, as a string. Example: "15174593"'),
        name: z.string().optional().describe('Display name of the assigned user or team. Example: "John Doe"'),
        email: z.string().optional().describe('Email of the assigned user. Present for user assignees only. Example: "john.doe@example.com"')
    })
    .describe('User or team the issue is currently assigned to.');

const IssueProjectSchema = z
    .object({
        id: z.string().describe('Numeric ID (as a string) of the project the issue belongs to. Example: "4512170111991808"'),
        name: z.string().optional().describe('Name of the project. Example: "nango-seed-project"'),
        slug: z.string().optional().describe('Slug of the project, unique within the organization. Example: "nango-seed-project"'),
        platform: z.string().optional().describe('Platform key of the project. Example: "node"')
    })
    .describe('The Sentry project the issue belongs to.');

const IssueMetadataSchema = z
    .object({
        title: z.string().optional().describe('Human-readable title generated by Sentry for the issue.'),
        type: z.string().optional().describe('Error type for error issues, usually the exception class. Example: "TypeError"'),
        value: z.string().optional().describe('Error value or message for error issues. Example: "undefined is not a function"'),
        filename: z.string().optional().describe('File in which the error occurred, when known.'),
        function: z.string().optional().describe('Function in which the error occurred, when known.')
    })
    .describe('Issue metadata extracted from the ingested event payload.');

const IssueReleaseSchema = z
    .object({
        version: z.string().optional().describe('Version string of the release. Example: "nango-seed-1.0.0"')
    })
    .describe('The first release in which the issue was seen.');

const IssueSchema = z
    .object({
        id: z.string().describe('Numeric issue ID as a string; used in Sentry API path parameters. Example: "7761433611"'),
        shortId: z.string().optional().describe('Human-readable issue short ID shown in the Sentry UI and permalinks. Example: "NANGO-SEED-PROJECT-1"'),
        title: z.string().optional().describe('Issue title, usually the error type and value. Example: "TypeError: undefined is not a function"'),
        culprit: z.string().optional().describe('Legacy culprit string describing where the error occurred.'),
        permalink: z.string().optional().describe('URL of the issue details page in Sentry.'),
        level: z.string().optional().describe('Severity level of the issue. Example: "error"'),
        status: z.string().optional().describe('Resolution status of the issue: "unresolved", "resolved" or "ignored".'),
        substatus: z.string().optional().describe('Sub-status of the issue, e.g. "archived_until_escalating" for ignored issues.'),
        logger: z.string().optional().describe("Logger that reported the issue's events, when set."),
        platform: z.string().optional().describe('Platform of the events grouped into this issue. Example: "node"'),
        type: z.string().optional().describe('Grouping type of the issue, e.g. "error" or "default".'),
        issueType: z.string().optional().describe('Fine-grained issue type. Example: "error"'),
        issueCategory: z.string().optional().describe('Issue category, e.g. "error", "performance" or "cron".'),
        priority: z.string().optional().describe('Issue priority: "high", "medium" or "low".'),
        count: z.string().optional().describe('Number of events grouped into this issue, serialized as a string. Example: "150"'),
        userCount: z.number().optional().describe('Number of distinct users affected by this issue.'),
        numComments: z.number().optional().describe('Number of comments on the issue.'),
        isPublic: z.boolean().optional().describe('Whether the issue has been shared publicly.'),
        isBookmarked: z.boolean().optional().describe("Whether the token's user has bookmarked the issue."),
        isSubscribed: z.boolean().optional().describe("Whether the token's user is subscribed to the issue."),
        hasSeen: z.boolean().optional().describe("Whether the token's user has seen the issue."),
        isUnhandled: z.boolean().optional().describe("Whether the issue's events were unhandled exceptions."),
        annotations: z.array(z.string()).optional().describe('Annotation strings attached to the issue, e.g. rendered links to external issues.'),
        project: IssueProjectSchema.optional().describe('The Sentry project the issue belongs to.'),
        metadata: IssueMetadataSchema.optional().describe('Issue metadata extracted from the ingested event payload.'),
        assignedTo: IssueAssigneeSchema.optional().describe('User or team the issue is currently assigned to. Omitted when unassigned.'),
        firstRelease: IssueReleaseSchema.optional().describe('The first release in which the issue was seen, when the issue is bound to a release.'),
        firstSeen: z.string().optional().describe('ISO-8601 timestamp of the first event grouped into this issue. Example: "2018-11-06T21:19:55Z"'),
        lastSeen: z.string().optional().describe('ISO-8601 timestamp of the most recent event grouped into this issue. Example: "2018-12-06T21:19:55Z"')
    })
    .describe('A Sentry issue (error group) from any project in the organization.');

// Internal provider response schemas. Unknown fields are stripped; fields that
// Sentry can return as explicit null are .nullable() and normalized to omission
// in the mapping below.
const SentryAssigneeSchema = z.object({
    type: z.string().optional(),
    id: z.union([z.string(), z.number()]).optional(),
    name: z.string().nullable().optional(),
    email: z.string().nullable().optional()
});

const SentryIssueSchema = z.object({
    id: z.union([z.string(), z.number()]),
    shortId: z.string().nullable().optional(),
    title: z.string().nullable().optional(),
    culprit: z.string().nullable().optional(),
    permalink: z.string().nullable().optional(),
    level: z.string().nullable().optional(),
    status: z.string().nullable().optional(),
    substatus: z.string().nullable().optional(),
    logger: z.string().nullable().optional(),
    platform: z.string().nullable().optional(),
    type: z.string().nullable().optional(),
    issueType: z.string().nullable().optional(),
    issueCategory: z.string().nullable().optional(),
    priority: z.string().nullable().optional(),
    count: z.union([z.string(), z.number()]).nullable().optional(),
    userCount: z.number().nullable().optional(),
    numComments: z.number().nullable().optional(),
    isPublic: z.boolean().nullable().optional(),
    isBookmarked: z.boolean().nullable().optional(),
    isSubscribed: z.boolean().nullable().optional(),
    hasSeen: z.boolean().nullable().optional(),
    isUnhandled: z.boolean().nullable().optional(),
    annotations: z.array(z.string()).nullable().optional(),
    project: z
        .object({
            id: z.union([z.string(), z.number()]),
            name: z.string().nullable().optional(),
            slug: z.string().nullable().optional(),
            platform: z.string().nullable().optional()
        })
        .nullable()
        .optional(),
    metadata: z
        .object({
            title: z.string().nullable().optional(),
            type: z.string().nullable().optional(),
            value: z.string().nullable().optional(),
            filename: z.string().nullable().optional(),
            function: z.string().nullable().optional()
        })
        .nullable()
        .optional(),
    assignedTo: SentryAssigneeSchema.nullable().optional(),
    firstRelease: z
        .object({
            version: z.string().nullable().optional()
        })
        .nullable()
        .optional(),
    firstSeen: z.string().nullable().optional(),
    lastSeen: z.string().nullable().optional()
});

const SentryOrganizationSchema = z.object({
    id: z.union([z.string(), z.number()]).optional(),
    slug: z.string()
});

function toIssue(issue: z.infer<typeof SentryIssueSchema>): z.infer<typeof IssueSchema> {
    return {
        id: String(issue.id),
        ...(issue.shortId != null && { shortId: issue.shortId }),
        ...(issue.title != null && { title: issue.title }),
        ...(issue.culprit != null && { culprit: issue.culprit }),
        ...(issue.permalink != null && { permalink: issue.permalink }),
        ...(issue.level != null && { level: issue.level }),
        ...(issue.status != null && { status: issue.status }),
        ...(issue.substatus != null && { substatus: issue.substatus }),
        ...(issue.logger != null && { logger: issue.logger }),
        ...(issue.platform != null && { platform: issue.platform }),
        ...(issue.type != null && { type: issue.type }),
        ...(issue.issueType != null && { issueType: issue.issueType }),
        ...(issue.issueCategory != null && { issueCategory: issue.issueCategory }),
        ...(issue.priority != null && { priority: issue.priority }),
        ...(issue.count != null && { count: String(issue.count) }),
        ...(issue.userCount != null && { userCount: issue.userCount }),
        ...(issue.numComments != null && { numComments: issue.numComments }),
        ...(issue.isPublic != null && { isPublic: issue.isPublic }),
        ...(issue.isBookmarked != null && { isBookmarked: issue.isBookmarked }),
        ...(issue.isSubscribed != null && { isSubscribed: issue.isSubscribed }),
        ...(issue.hasSeen != null && { hasSeen: issue.hasSeen }),
        ...(issue.isUnhandled != null && { isUnhandled: issue.isUnhandled }),
        ...(issue.annotations != null && { annotations: issue.annotations }),
        ...(issue.project != null && {
            project: {
                id: String(issue.project.id),
                ...(issue.project.name != null && { name: issue.project.name }),
                ...(issue.project.slug != null && { slug: issue.project.slug }),
                ...(issue.project.platform != null && { platform: issue.project.platform })
            }
        }),
        ...(issue.metadata != null && {
            metadata: {
                ...(issue.metadata.title != null && { title: issue.metadata.title }),
                ...(issue.metadata.type != null && { type: issue.metadata.type }),
                ...(issue.metadata.value != null && { value: issue.metadata.value }),
                ...(issue.metadata.filename != null && { filename: issue.metadata.filename }),
                ...(issue.metadata.function != null && { function: issue.metadata.function })
            }
        }),
        ...(issue.assignedTo != null && {
            assignedTo: {
                ...(issue.assignedTo.type != null && { type: issue.assignedTo.type }),
                ...(issue.assignedTo.id != null && { id: String(issue.assignedTo.id) }),
                ...(issue.assignedTo.name != null && { name: issue.assignedTo.name }),
                ...(issue.assignedTo.email != null && { email: issue.assignedTo.email })
            }
        }),
        ...(issue.firstRelease?.version != null && { firstRelease: { version: issue.firstRelease.version } }),
        ...(issue.firstSeen != null && { firstSeen: issue.firstSeen }),
        ...(issue.lastSeen != null && { lastSeen: issue.lastSeen })
    };
}

const sync = createSync({
    description: 'Sync issues (error groups) across all projects in the organization.',
    version: '1.0.0',
    frequency: 'every hour',
    autoStart: true,
    scopes: ['event:read'],
    models: {
        Issue: IssueSchema
    },

    exec: async (nango) => {
        // A Sentry API token is scoped to a single organization; resolve that
        // organization once and use its slug for the issues crawl.
        const organizationsConfig: ProxyConfiguration = {
            // https://docs.sentry.io/api/users/list-your-organizations/
            endpoint: '/0/organizations/',
            retries: 3
        };
        const organizationsResponse = await nango.get(organizationsConfig);
        const organizationsParsed = z.array(SentryOrganizationSchema).safeParse(organizationsResponse.data);
        if (!organizationsParsed.success) {
            throw new Error(`Failed to parse the Sentry organizations response: ${organizationsParsed.error.message}`);
        }
        const [organization] = organizationsParsed.data;
        if (!organization) {
            throw new Error('No Sentry organization is accessible for this connection.');
        }

        // Full refresh: open the delete-tracking window only after the
        // organization prerequisite has been resolved successfully.
        await nango.trackDeletesStart('Issue');

        const issuesConfig: ProxyConfiguration = {
            // https://docs.sentry.io/api/events/list-an-organizations-issues/
            endpoint: `/0/organizations/${encodeURIComponent(organization.slug)}/issues/`,
            params: {
                // Empty query bypasses the default "is:unresolved" filter so
                // resolved and ignored issues are synced too.
                query: '',
                sort: 'date'
            },
            paginate: {
                type: 'link',
                link_rel_in_response_header: 'next',
                limit_name_in_request: 'limit',
                limit: 100
            },
            retries: 3
        };

        for await (const issuesPage of nango.paginate<unknown>(issuesConfig)) {
            const issuesParsed = z.array(SentryIssueSchema).safeParse(issuesPage);
            if (!issuesParsed.success) {
                // Fail loudly: skipping an unparseable record inside a
                // delete-tracked crawl would mark it as deleted at trackDeletesEnd.
                throw new Error(`Failed to parse a Sentry issues page: ${issuesParsed.error.message}`);
            }
            const issues = issuesParsed.data.map(toIssue);
            if (issues.length === 0) {
                continue;
            }
            await nango.batchSave(issues, 'Issue');
        }

        // The crawl completed; close the delete-tracking window exactly once.
        await nango.trackDeletesEnd('Issue');
    }
});

export type NangoSyncLocal = Parameters<(typeof sync)['exec']>[0];
export default sync;
